#!/usr/bin/env python3
"""Assign a permanent identifier to every scenario that does not have one.

A scenario is referenced by tests, merge requests and verdicts, so the reference
has to survive the scenario being renamed or moved to another file. A path and a
title do neither: both invite editing, and three titles already collide across
the corpus.

So each scenario carries a tag, `@PREFIX-n`, where the prefix names the area and
the number is sequential within it. The number is **permanent**: this tool only
ever assigns one to a scenario that has none, and `check-ids.py` refuses a
number that was assigned to something else before.

    python3 features/tools/assign-ids.py          # report what would be assigned
    python3 features/tools/assign-ids.py --write  # assign and update the registry
"""
from __future__ import annotations

import glob
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(BASE)
REGISTRY = os.path.join(BASE, "IDS.md")

PREFIX = {
    "apps": "APP", "branding": "BRAND", "compatibility": "COMPAT",
    "connectivity": "NET", "device": "DEV", "identity": "ID",
    "privacy": "PRIV", "process": "PROC", "setup": "SETUP",
    "system": "SYS", "updates": "UPD",
}

SCENARIO = re.compile(r"^(\s*)Scenario(?: Outline)?:\s*(.+?)\s*$")
TAG_LINE = re.compile(r"^\s*@[\w@ -]+\s*$")
ID_TAG = re.compile(r"@([A-Z]+)-(\d+)\b")


def area(path: str) -> str:
    folder = os.path.relpath(path, BASE).split(os.sep)[0]
    if folder not in PREFIX:
        raise SystemExit(f"{path}: no prefix declared for area {folder!r}")
    return PREFIX[folder]


def read_registry() -> dict[str, str]:
    """Assigned identifier -> the title it was first given to."""
    assigned = {}
    if not os.path.exists(REGISTRY):
        return assigned
    for line in open(REGISTRY, errors="ignore"):
        m = re.match(r"^\| `(@[A-Z]+-\d+)` \| (.+?) \|", line)
        if m:
            assigned[m.group(1)] = m.group(2)
    return assigned


def scan():
    """Yield (path, line index, indent, title, existing id or None)."""
    for path in sorted(glob.glob(os.path.join(BASE, "**", "*.feature"), recursive=True)):
        lines = open(path, errors="ignore").read().splitlines()
        for i, line in enumerate(lines):
            m = SCENARIO.match(line)
            if not m:
                continue
            existing = None
            j = i - 1
            while j >= 0 and TAG_LINE.match(lines[j]):
                found = ID_TAG.search(lines[j])
                if found:
                    existing = found.group(0)
                j -= 1
            yield path, i, m.group(1), m.group(2), existing


def main(argv: list[str]) -> int:
    write = "--write" in argv
    assigned = read_registry()
    used = {int(k.split("-")[1]): k for k in assigned if k.startswith("@")}
    next_free: dict[str, int] = {}
    for key in assigned:
        prefix, number = key[1:].split("-")
        next_free[prefix] = max(next_free.get(prefix, 0), int(number))

    todo = []
    for path, i, indent, title, existing in scan():
        if existing:
            continue
        prefix = area(path)
        next_free[prefix] = next_free.get(prefix, 0) + 1
        todo.append((path, i, indent, title, f"@{prefix}-{next_free[prefix]}"))

    if not todo:
        print("every scenario already carries an identifier")
        return 0

    if not write:
        print(f"{len(todo)} scenarios would be assigned an identifier; "
              f"re-run with --write")
        for path, _, _, title, key in todo[:10]:
            print(f"  {key:12} {os.path.relpath(path, REPO_ROOT)} :: {title[:44]}")
        if len(todo) > 10:
            print(f"  ... and {len(todo) - 10} more")
        return 0

    by_file: dict[str, list] = {}
    for path, i, indent, title, key in todo:
        by_file.setdefault(path, []).append((i, indent, title, key))
    for path, items in by_file.items():
        lines = open(path, errors="ignore").read().splitlines()
        for i, indent, _title, key in sorted(items, reverse=True):
            lines.insert(i, f"{indent}{key}")
        with open(path, "w") as fh:
            fh.write("\n".join(lines) + "\n")

    rows = dict(assigned)
    for _path, _i, _indent, title, key in todo:
        rows[key] = title
    with open(REGISTRY, "w") as fh:
        fh.write("# Scenario identifiers\n\n")
        fh.write("<!-- generated by features/tools/assign-ids.py - do not edit by hand -->\n\n")
        fh.write("A number is **never reused**, even when the scenario it named is deleted:\n")
        fh.write("a merge request or a verdict citing it must keep resolving to what it meant.\n\n")
        fh.write("| id | first assigned to |\n|---|---|\n")
        for key in sorted(rows, key=lambda k: (k.split("-")[0], int(k.split("-")[1]))):
            fh.write(f"| `{key}` | {rows[key]} |\n")

    print(f"assigned {len(todo)} identifiers, registry now holds {len(rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
