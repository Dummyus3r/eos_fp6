#!/usr/bin/env python3
"""Generate COVERAGE.md from the `# Proven by:` headers of the requirements .feature files.

Each requirement file is the single source of truth for its own citations;
this report is derived from them, so it cannot drift on its own — re-run it
after adding, proving, or re-scoping a requirement.

    python3 requirements/tools/gen-coverage.py

Exits non-zero if any citation points at a features/ file that does not
exist, so this can run as a CI check, not just a report generator.
"""
import re, os, glob, sys, datetime

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(BASE)

NONE_YET = re.compile(r'\(none yet.*?\)', re.IGNORECASE)


def parse(path):
    """Return (title, cited_paths) for one requirement .feature file.

    The `# Proven by:` header may continue on following comment lines,
    indented to line up under it; comment lines after the citation block
    (annotations, known-exception notes) are ignored."""
    cited, in_block, title = [], False, ''
    for line in open(path):
        if line.startswith('#'):
            body = line[1:].strip()
            if body.startswith('Proven by:'):
                in_block = True
                body = body[len('Proven by:'):].strip()
            elif in_block and not re.match(r'^[A-Za-z0-9_./-]+\.feature', body) \
                    and ',' not in line[:4]:
                in_block = False
            if in_block:
                for part in NONE_YET.sub('', body).split(','):
                    part = part.strip().rstrip(',')
                    if part.endswith('.feature'):
                        cited.append(part)
        elif line.startswith('Feature:'):
            title = line[len('Feature:'):].strip()
            break
    return title, cited


def main():
    rows, broken = [], []
    for p in sorted(glob.glob(os.path.join(BASE, '**', '*.feature'), recursive=True)):
        rel = os.path.relpath(p, BASE)
        title, cited = parse(p)
        resolved = []
        for c in cited:
            full = os.path.join(REPO_ROOT, c)
            exists = os.path.isfile(full)
            resolved.append((c, exists))
            if not exists:
                broken.append((rel, c))
        rows.append((rel, title, resolved))

    proven = [r for r in rows if any(ok for _, ok in r[2])]
    unproven = [r for r in rows if not any(ok for _, ok in r[2])]

    out = ['# Requirements coverage', '',
           'Generated by `requirements/tools/gen-coverage.py` — do not edit by hand.',
           f'Generated: {datetime.date.today().isoformat()}', '',
           f'{len(proven)} of {len(rows)} requirements are cited by at least one '
           'existing `features/` file. The rest are declared promises with no '
           'proving spec yet — that gap is the point of this report, not a defect '
           'in it.', '']

    out += ['## Proven', '', '| Requirement | Feature | Cited by |', '|---|---|---|']
    for rel, title, resolved in proven:
        cites = ', '.join(f'`{c}`' for c, ok in resolved if ok)
        out.append(f'| `{rel}` | {title} | {cites} |')

    out += ['', '## Not yet proven', '',
            '| Requirement | Feature |', '|---|---|']
    for rel, title, _ in unproven:
        out.append(f'| `{rel}` | {title} |')

    if broken:
        out += ['', '## Broken citations', '',
                'A `# Proven by:` line points at a `features/` file that does not exist.'
                ' Fix the citation or the file, not this report.', '',
                '| Requirement | Cites |', '|---|---|']
        for rel, c in broken:
            out.append(f'| `{rel}` | `{c}` |')

    with open(os.path.join(BASE, 'COVERAGE.md'), 'w') as f:
        f.write('\n'.join(out) + '\n')

    print(f'{len(proven)} proven, {len(unproven)} unproven, {len(broken)} broken citation(s)')
    if broken:
        for rel, c in broken:
            print(f'  BROKEN: {rel} cites missing {c}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
