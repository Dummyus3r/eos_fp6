#!/usr/bin/env python3
"""Assign a permanent identifier to every requirement.

A requirement is what a merge request, a test or a verdict cites — "this serves
R7". So the citable unit here is the `Feature:`, not the scenarios under it:
those are facets of one requirement, and citing a facet would say less than
citing what it is a facet of.

Identifiers are `@R-n`, flat rather than per-area: there are a dozen requirements,
and a short number is easier to say out loud than a prefixed one. It is
**permanent** — this tool only assigns to a requirement that has none, and
never renumbers.

    python3 requirements/tools/assign-ids.py          # report
    python3 requirements/tools/assign-ids.py --write  # assign and update IDS.md
"""
from __future__ import annotations

import glob
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(BASE)
REGISTRY = os.path.join(BASE, "IDS.md")

FEATURE = re.compile(r"^Feature:\s*(.+?)\s*$")
TAG_LINE = re.compile(r"^\s*@[\w@ -]+\s*$")
ID_TAG = re.compile(r"@R-\d+\b")


def read_registry() -> dict[str, str]:
    assigned = {}
    if os.path.exists(REGISTRY):
        for line in open(REGISTRY, errors="ignore"):
            m = re.match(r"^\| `(@R-\d+)` \| (.+?) \|", line)
            if m:
                assigned[m.group(1)] = m.group(2)
    return assigned


def scan():
    """Yield (path, line index of Feature, title, existing id or None)."""
    for path in sorted(glob.glob(os.path.join(BASE, "**", "*.feature"), recursive=True)):
        lines = open(path, errors="ignore").read().splitlines()
        for i, line in enumerate(lines):
            m = FEATURE.match(line)
            if not m:
                continue
            existing, j = None, i - 1
            while j >= 0 and TAG_LINE.match(lines[j]):
                found = ID_TAG.search(lines[j])
                if found:
                    existing = found.group(0)
                j -= 1
            yield path, i, m.group(1), existing
            break   # one Feature per file, by convention


def main(argv: list[str]) -> int:
    write = "--write" in argv
    assigned = read_registry()
    highest = max((int(k[3:]) for k in assigned), default=0)

    todo = []
    for path, i, title, existing in scan():
        if existing:
            continue
        highest += 1
        todo.append((path, i, title, f"@R-{highest}"))

    if not todo:
        print("every requirement already carries an identifier")
        return 0
    if not write:
        print(f"{len(todo)} requirements would be assigned an identifier; re-run with --write")
        for path, _i, title, key in todo:
            print(f"  {key:7} {os.path.relpath(path, REPO_ROOT)} :: {title[:44]}")
        return 0

    for path, i, _title, key in todo:
        lines = open(path, errors="ignore").read().splitlines()
        # the tag goes on the line above Feature:, joining the tags already there
        if i > 0 and TAG_LINE.match(lines[i - 1]):
            lines[i - 1] = f"{lines[i - 1].rstrip()} {key}"
        else:
            lines.insert(i, key)
        with open(path, "w") as fh:
            fh.write("\n".join(lines) + "\n")

    rows = dict(assigned)
    for _path, _i, title, key in todo:
        rows[key] = title
    with open(REGISTRY, "w") as fh:
        fh.write("# Requirement identifiers\n\n")
        fh.write("<!-- generated by requirements/tools/assign-ids.py - do not edit by hand -->\n\n")
        fh.write("A number is **never reused**, even when the requirement it named is dropped:\n")
        fh.write("a merge request or a verdict citing it must keep resolving to what it meant.\n\n")
        fh.write("| id | requirement |\n|---|---|\n")
        for key in sorted(rows, key=lambda k: int(k[3:])):
            fh.write(f"| `{key}` | {rows[key]} |\n")

    print(f"assigned {len(todo)} identifiers, registry now holds {len(rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
